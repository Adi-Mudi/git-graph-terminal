//! W2 integration test (T2): the **real** `data::commits → layout::layout()` path.
//!
//! `golden_layout.rs` pins `layout()` alone: it hand-builds a commit list from the
//! golden JSON. This test closes the F3 gap by running the actual `git` data layer:
//!
//! 1. for every committed G8 golden fixture, run `data::commits()` on the matching
//!    fixture repository, feed the result straight into `layout::layout()` and assert
//!    it still equals the golden JSON (shared helpers in [`common`]);
//! 2. render a real layout into a ratatui [`TestBackend`] and assert the key glyphs
//!    are actually painted (`●` nodes and the `◯` HEAD node).
//!
//! The fixture repositories are git-ignored and generated by
//! `tools/g8-dump/make-fixtures.sh` with pinned hashes, so the test regenerates them
//! only when missing (git required; node is not).
//!
//! The crate has no library target, so the modules under test are pulled in with
//! `#[path]`. Only the pieces the tests need are included; `App`/`main.rs` stay out.

#[allow(dead_code)] // `data.rs` is FROZEN and shared; the tests only use part of it.
