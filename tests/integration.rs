/// Run `make-fixtures.sh` at most once per test process.
static FIXTURES: Once = Once::new();

/// `tests/fixtures/repos` (git-ignored, generated).
fn fixtures_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/repos")
}

/// Regenerate the deterministic G8 fixture repositories if they are missing.
fn ensure_fixtures() {
    FIXTURES.call_once(|| {
        let root = fixtures_root();
        if root.join("linear").join(".git").exists()
            && root.join("branch-merge-rebase").join(".git").exists()
        {
            return;
        }
        let script = Path::new(env!("CARGO_MANIFEST_DIR")).join("tools/g8-dump/make-fixtures.sh");
        let output = Command::new("bash")
            .arg(&script)
            .output()
            .unwrap_or_else(|error| panic!("cannot run {}: {error}", script.display()));
        assert!(
            output.status.success(),
            "make-fixtures.sh failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    });
}

/// Every committed golden fixture, sorted by file name.
fn golden_paths() -> Vec<PathBuf> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/golden");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", dir.display()))
        .map(|entry| entry.expect("dir entry").path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
        .collect();
    paths.sort();
    assert_eq!(paths.len(), 3, "expected the three committed G8 goldens");
    paths
}

/// Load `repo.path` from a golden (relative to the manifest dir) and its commit list.
///
/// The truncated fixture dumps the *same* repository through a smaller commit window,
/// so its real `git log` is longer than the golden: keep only the golden's hashes, in
/// the order `data::commits` returned them (which the assertion below then pins).
fn commits_for_golden(json: &common::Json, golden: &common::Golden) -> Vec<Commit> {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join(json.get("repo").get("path").as_str());
    let mut commits = data::commits(&repo)
        .unwrap_or_else(|error| panic!("data::commits({}) failed: {error}", repo.display()));

    if commits.len() != golden.commit_hashes.len() {
        let wanted: HashSet<&str> = golden.commit_hashes.iter().map(String::as_str).collect();
        commits.retain(|commit| wanted.contains(commit.hash.as_str()));
    }

    let got: Vec<&str> = commits.iter().map(|commit| commit.hash.as_str()).collect();
    let want: Vec<&str> = golden.commit_hashes.iter().map(String::as_str).collect();
    assert_eq!(got, want, "data::commits order vs golden repo.commitHashes");

    commits
}

#[test]
fn data_to_layout_matches_every_golden_fixture() {
    ensure_fixtures();

    for path in golden_paths() {
        let json = read_golden(&path);
        let name = json.get("fixture").as_str().to_string();
        let golden = golden_from(&json);
        let commits = commits_for_golden(&json, &golden);

        // The real data layer observed HEAD and the annotated tags the reference saw.
        assert!(
            commits
                .iter()
                .any(|commit| commit.refs.iter().any(|r| r.starts_with("HEAD ->"))),
            "{name}: data::commits must surface the HEAD decoration"
        );

        let graph = layout(&commits, &LayoutOpts::default());
        let null_parents = assert_layout_matches(&name, &graph, &commits, &golden);
        eprintln!(
            "ok   data→layout parity: {name} ({} rows, {} NULL parents)",
            graph.rows.len(),
            null_parents
        );
    }
}

#[test]
fn truncated_fixture_keeps_the_out_of_window_parent_sentinel() {
    ensure_fixtures();

    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/golden/branch-merge-rebase-truncated.json");
    let json = read_golden(&path);
    let golden = golden_from(&json);
    let commits = commits_for_golden(&json, &golden);
    let graph = layout(&commits, &LayoutOpts::default());

    let null_parents =
        assert_layout_matches("branch-merge-rebase-truncated", &graph, &commits, &golden);
    assert!(
        null_parents >= 1,
        "the truncated window must reproduce the parents: [-1] sentinel"
    );
}

#[test]
fn render_smoke_paints_graph_glyphs() {
    ensure_fixtures();

    // `branch-merge-rebase` has a HEAD commit, so both node glyphs appear.
    let repo = fixtures_root().join("branch-merge-rebase");
    let commits = data::commits(&repo).expect("fixture commits");
    let graph = layout(&commits, &LayoutOpts::default());

    let head = graph
        .rows
        .iter()
        .find_map(|row| row.vertex.filter(|vertex| vertex.is_head))
        .expect("fixture must have a HEAD vertex");

    let text = render_to_text(&graph);
    assert!(
        text.contains('●'),
        "render must paint filled commit nodes (●):\n{text}"
    );
    assert!(
        text.contains('◯'),
        "render must paint the open HEAD node (◯):\n{text}"
    );
    assert!(
        text.contains('│') || text.contains('─') || text.contains('╮'),
        "render must connect nodes with box-drawing lines:\n{text}"
    );

    // The HEAD vertex's own grid cell (2 cells per lane) must hold the open node.
    let lines: Vec<&str> = text.lines().collect();
    let head_cell = lines[head.row as usize]
        .chars()
        .nth(2 * head.lane as usize)
        .expect("HEAD cell is inside the rendered width");
    assert_eq!(
        head_cell, '◯',
        "HEAD vertex cell must show the open node:\n{text}"
    );

    eprintln!("ok   render smoke:\n{text}");
}

/// Render `graph` into a ratatui `TestBackend` and return the buffer as text.
fn render_to_text(graph: &GraphLayout) -> String {
    use render::cell::graph_cells;

    let width = graph_cells(graph.max_lane).max(1) as u16;
    let height = graph.rows.len().max(1) as u16;
    let backend = TestBackend::new(width, height);
    let mut terminal = Terminal::new(backend).expect("TestBackend is infallible");

    terminal
        .draw(|frame| {
            let area = frame.area();
            frame.render_widget(
                GraphWidget {
                    layout: graph,
                    tier: GlyphTier::Unicode,
                    selected: None,
                    uncommitted: None,
                    scroll: 0,
                    colour: false,
                },
                area,
            );
        })
        .expect("TestBackend draw is infallible");

    let buffer = terminal.backend().buffer();
    let mut text = String::new();
    for y in 0..buffer.area.height {
        for x in 0..buffer.area.width {
            text.push_str(buffer[(x, y)].symbol());
        }
        text.push('\n');
    }
    text
}
