use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Once;

use app::{reduce, Action, AppState, EXPANDED_EXTRA_ROWS};
use layout::{NavDir, NO_ROW};
/// Run `make-fixtures.sh` at most once per test process.
static FIXTURES: Once = Once::new();

/// `tests/fixtures/repos` (git-ignored, generated).
fn fixtures_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/repos")
}

/// Regenerate the deterministic G8 fixture repositories if they are missing.
fn ensure_fixtures() {
    FIXTURES.call_once(|| {
        let root = fixtures_root();
        if root.join("linear").join(".git").exists()
            && root.join("branch-merge-rebase").join(".git").exists()
        {
            return;
        }
        let script = Path::new(env!("CARGO_MANIFEST_DIR")).join("tools/g8-dump/make-fixtures.sh");
        let output = Command::new("bash")
            .arg(&script)
            .output()
            .unwrap_or_else(|error| panic!("cannot run {}: {error}", script.display()));
        assert!(
            output.status.success(),
            "make-fixtures.sh failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    });
}

/// The `branch-merge-rebase` fixture (contains one merge commit).
fn merge_fixture() -> PathBuf {
    ensure_fixtures();
    fixtures_root().join("branch-merge-rebase")
}

/// Index of the fixture's merge commit (the only row with two parents).
fn merge_row(state: &AppState) -> usize {
    state
        .rows
        .iter()
        .position(|commit| commit.parents.len() > 1)
        .expect("branch-merge-rebase must contain a merge commit")
}

#[test]
fn app_state_loads_the_merge_fixture_and_matches_the_layout() {
    let state = AppState::load(&merge_fixture());

    assert!(state.status.error.is_none(), "{:?}", state.status.error);
    assert_eq!(
        state.layout.rows.len(),
        state.rows.len(),
        "every loaded commit gets exactly one laid-out row"
    );
    assert_eq!(state.status.commits, state.rows.len());
    assert!(state.status.head.len() >= 7, "HEAD hash is surfaced");
    assert!(!state.status.branch.is_empty());
    assert!(
        merge_row(&state) > 0,
        "the merge is not the first row, so nav has room to move"
    );
}

#[test]
fn branch_nav_crosses_the_merge_in_a_real_repo() {
    let mut state = AppState::load(&merge_fixture());
    let merge = merge_row(&state);
    state.selected = merge as u32;

    // Right / Ctrl+Down = first parent (`layout::nav(Down)`).
    let first_parent = layout::nav(&state.layout, state.selected, NavDir::Down);
    assert_ne!(first_parent, NO_ROW, "the merge has a first parent");

    reduce(&mut state, Action::NextBranch, Path::new("."));
    assert_eq!(state.selected, first_parent);
    assert_eq!(
        state.rows[state.selected as usize].hash, state.rows[merge].parents[0],
        "NextBranch lands on the first parent by hash"
    );

    // Left / Ctrl+Up = first child; the merge is m4's only child, so we return.
    reduce(&mut state, Action::PrevBranch, Path::new("."));
    assert_eq!(
        state.rows[state.selected as usize].hash, state.rows[merge].hash,
        "PrevBranch returns to the merge commit"
    );
    assert_eq!(state.selected, merge as u32);
}

#[test]
fn expand_and_collapse_change_the_viewport_height() {
    let mut state = AppState::load(&merge_fixture());
    let before = state.display_rows();

    state.selected = 0;
    reduce(&mut state, Action::ToggleExpand, Path::new("."));
    assert!(state.expanded.contains(&0));
    assert_eq!(state.display_rows(), before + EXPANDED_EXTRA_ROWS);
    assert_eq!(state.row_height(0), 1 + EXPANDED_EXTRA_ROWS);
    assert_eq!(state.row_top(1), 1 + EXPANDED_EXTRA_ROWS);

    reduce(&mut state, Action::ToggleExpand, Path::new("."));
    assert!(state.expanded.is_empty());
    assert_eq!(state.display_rows(), before, "collapse restores the height");
    assert_eq!(state.row_height(0), 1);
}

#[test]
fn scrolling_follows_the_selection_over_the_fixture() {
    let mut state = AppState::load(&merge_fixture());
    state.status.height = 4; // a deliberately small viewport
    let last = state.rows.len() as u32 - 1;

    reduce(&mut state, Action::Bottom, Path::new("."));
    assert_eq!(state.selected, last);
    // The selected row must sit inside [scroll, scroll + height).
    let top = state.row_top(state.selected);
    let bottom = top + state.row_height(state.selected);
    assert!(top >= state.scroll, "selection is not above the viewport");
    assert!(
        bottom <= state.scroll + 4,
        "selection is not below the viewport"
    );

    reduce(&mut state, Action::Top, Path::new("."));
    assert_eq!(state.selected, 0);
    assert_eq!(state.scroll, 0);
}

#[test]
fn mock_state_accepts_scripted_keys_through_the_keymap() {
    // End-to-end: a crossterm `KeyEvent` -> `keymap::action_for` -> `reduce`,
    // exactly the path `main.rs` drives from its event loop (T1 + T2).
    use crossterm::event::{KeyCode, KeyEvent, KeyModifiers};

    let mut state = AppState::demo();
    assert_eq!(state.rows.len(), 8);

    for code in [KeyCode::Char('j'), KeyCode::Down] {
        let action = keymap::action_for(KeyEvent::new(code, KeyModifiers::NONE))
            .expect("j / Down are bound");
        reduce(&mut state, action, Path::new("."));
    }
    assert_eq!(state.selected, 2, "j then Down move the selection twice");

    let expand = keymap::action_for(KeyEvent::new(KeyCode::Enter, KeyModifiers::NONE))
        .expect("Enter is bound");
    reduce(&mut state, expand, Path::new("."));
    assert!(
        state.expanded.contains(&2),
        "Enter expands the selected row"
    );

    // Shift+s is previous, no shift is next (R1.2) — the mock has a stash row.
    let stash_next =
        keymap::action_for(KeyEvent::new(KeyCode::Char('s'), KeyModifiers::NONE)).unwrap();
    let stash_prev =
        keymap::action_for(KeyEvent::new(KeyCode::Char('s'), KeyModifiers::SHIFT)).unwrap();
    assert_eq!(stash_next, Action::StashNext, "no Shift = next");
    assert_eq!(stash_prev, Action::StashPrev, "Shift = previous (R1.2)");
}

#[test]
fn stash_navigation_is_a_noop_when_the_fixture_has_no_stash() {
    // `branch-merge-rebase` has no stash entry, so the R1.2 stash direction and
    // wraparound are covered by the hand-built unit tests in `src/app.rs`
    // (`stash_direction_and_wrap_match_r1_2`). Here we only pin the no-op path.
    let mut state = AppState::load(&merge_fixture());
    if state.rows.iter().any(|commit| {
        commit
            .refs
            .iter()
            .any(|reference| reference.starts_with("refs/stash") || reference.starts_with("stash@"))
    }) {
        eprintln!("note: fixture gained a stash row; R1.2 is exercised in src/app.rs");
        return;
    }
    state.selected = 1;
    reduce(&mut state, Action::StashNext, Path::new("."));
    reduce(&mut state, Action::StashPrev, Path::new("."));
    assert_eq!(state.selected, 1, "no stash rows: stash nav is a no-op");
}
