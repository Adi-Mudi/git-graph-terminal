//! W4 integration test (T4): [`AppState`] over a **real** fixture repository.
//!
//! `src/app.rs`'s unit tests use hand-built commit lists. This test closes the
//! gap by running the actual `git` data layer through the W4 interaction core:
//!
//! 1. [`AppState::load`] on the committed `branch-merge-rebase` G8 fixture must
//!    line the rows up with the laid-out graph;
//! 2. [`Action::NextBranch`] / [`Action::PrevBranch`] must walk the merge across
//!    its first parent and back, by hash;
//! 3. expand/collapse must stretch the viewport by `EXPANDED_EXTRA_ROWS`;
//! 4. the follow-the-selection scroll must keep the selection inside the viewport.
//!
//! The fixture repositories are git-ignored and generated by
//! `tools/g8-dump/make-fixtures.sh` with pinned hashes, so the test regenerates
//! them only when missing (git required; node is not).
//!
//! The crate has no library target, so the modules under test are pulled in with
//! `#[path]`. `main.rs` stays out; `app.rs` needs `render::mock` for `demo()`,
//! so that one module is included too.

